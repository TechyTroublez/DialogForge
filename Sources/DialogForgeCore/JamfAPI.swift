import Foundation

/// Pure helpers for the Jamf Pro API. Networking lives in the app; this builds and reads payloads.
public enum JamfAPI {
    public enum Priority: String, CaseIterable, Identifiable {
        case before = "BEFORE"
        case after = "AFTER"
        case atReboot = "AT_REBOOT"

        public var id: String { rawValue }

        public var label: String {
            switch self {
            case .before: return "Before"
            case .after: return "After"
            case .atReboot: return "At Reboot"
            }
        }
    }

    /// Accepts "company.jamfcloud.com", "https://jamf.example.com:8443/" and similar.
    public static func baseURL(from text: String) -> URL? {
        var value = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !value.isEmpty else { return nil }
        if !value.contains("://") { value = "https://" + value }
        while value.hasSuffix("/") { value.removeLast() }
        guard let url = URL(string: value), let scheme = url.scheme, scheme == "https" || scheme == "http",
              let host = url.host, !host.isEmpty else { return nil }
        return url
    }

    /// The body for `POST /api/v1/scripts` and `PUT /api/v1/scripts/{id}`.
    public static func scriptPayload(project: FlowProject, name: String, priority: Priority = .after) -> JSONValue {
        var members: [JSONMember] = [
            JSONMember("name", .string(name)),
            JSONMember("info", .string("Generated by \(ScriptGenerator.generatorName)")),
            JSONMember("notes", .string(project.notes)),
            JSONMember("priority", .string(priority.rawValue))
        ]
        for parameter in project.parameters.sorted(by: { $0.index < $1.index }) where (4...11).contains(parameter.index) {
            members.append(JSONMember("parameter\(parameter.index)", .string(parameter.label)))
        }
        members.append(JSONMember("scriptContents", .string(ScriptGenerator.script(for: project))))
        return .object(members)
    }

    /// Path and query for finding a script by exact name.
    public static func scriptSearchPath(name: String) -> String {
        let escaped = name.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
        var allowed = CharacterSet.alphanumerics
        allowed.insert(charactersIn: "-._~")
        let filter = "name==\"\(escaped)\""
        let encoded = filter.addingPercentEncoding(withAllowedCharacters: allowed) ?? filter
        return "/api/v1/scripts?page=0&page-size=10&filter=" + encoded
    }

    /// Reads the ID of the first result from a `GET /api/v1/scripts` response.
    public static func firstScriptID(in response: JSONValue) -> String? {
        guard let results = response["results"]?.arrayValue, let first = results.first else { return nil }
        return first["id"]?.stringValue
    }
}
