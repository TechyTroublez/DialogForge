import Foundation

/// Generates a self-contained zsh script from a flow, ready to upload to Jamf Pro.
public enum ScriptGenerator {
    public static let generatorName = "DialogForge"

    // MARK: Effective dialog

    /// The dialog a step really launches: progress steps gain their task list, progress bar
    /// and command file; notification steps gain `--notification`.
    public static func effectiveSpec(for step: FlowStep, commandFile: String = "${commandFile}") -> DialogSpec {
        var spec = step.dialog
        switch step.kind {
        case .progress:
            spec.cards = []
            spec.cardStyle = ""
            spec.items[ItemCatalog.listItem.key] = step.tasks.map { task in
                var item = DialogItem(id: task.id)
                item["title"] = task.title
                item["subtitle"] = task.subtitle
                item["icon"] = task.icon
                item["status"] = "pending"
                return item
            }
            spec.options["progress"] = String(max(step.tasks.count, 1))
            spec.options["commandfile"] = commandFile
            spec.options["button1disabled"] = ""
            spec.options.removeValue(forKey: "notification")
        case .notification:
            spec.cards = []
            spec.cardStyle = ""
            spec.options["notification"] = ""
        default:
            spec.options.removeValue(forKey: "notification")
        }
        return spec
    }

    // MARK: Script

    public static func script(for project: FlowProject) -> String {
        let steps = project.steps.filter { $0.enabled }
        let names = Dictionary(steps.enumerated().map { ($0.element.id, "step_\($0.offset + 1)") },
                               uniquingKeysWith: { first, _ in first })
        let settings = project.settings
        let usesDialog = steps.contains { $0.usesDialog }
        let usesJamf = steps.contains { step in
            step.kind == .jamf || step.tasks.contains { $0.action == .policyEvent || $0.action == .policyID }
        } || (usesDialog && settings.installMethod == .jamfPolicy)

        var out: [String] = []
        out.append("#!/bin/zsh --no-rcs")
        out.append("#")
        out.append("# " + oneLine(project.name))
        if !settings.organisation.isEmpty { out.append("# " + oneLine(settings.organisation)) }
        for line in project.notes.split(separator: "\n", omittingEmptySubsequences: false) where !project.notes.isEmpty {
            out.append("# " + line)
        }
        out.append("#")
        out.append("# Generated by \(generatorName). Edit the flow in \(generatorName) rather than this file.")
        let parameters = project.parameters.sorted { $0.index < $1.index }
        if !parameters.isEmpty {
            out.append("#")
            out.append("# Jamf Pro script parameters:")
            for parameter in parameters {
                var line = "#   Parameter \(parameter.index): \(oneLine(parameter.label))"
                if !parameter.defaultValue.isEmpty { line += " (default: \(oneLine(parameter.defaultValue)))" }
                out.append(line)
            }
        }
        out.append("#")
        out.append("")
        out.append("scriptName=" + Shell.quote(project.name))
        out.append("scriptLog=" + Shell.quote(settings.logFile.isEmpty ? "/dev/null" : settings.logFile))
        if usesDialog {
            out.append("dialogBinary=" + Shell.quote(settings.dialogPath))
            out.append("minimumDialogVersion=" + Shell.quote(settings.minimumVersion))
            out.append("runDialogAsUser=" + (settings.runAsUser ? "true" : "false"))
        }
        if usesJamf { out.append("jamfBinary=\"/usr/local/bin/jamf\"") }
        out.append("commandFile=\"\"")
        out.append("temporaryFiles=()")
        out.append("")

        if !parameters.isEmpty {
            out.append(banner("Jamf Pro parameters"))
            for parameter in parameters where Shell.isValidVariableName(parameter.variable) {
                out.append("\(parameter.variable)=\"${\(parameter.index)}\"")
                if !parameter.defaultValue.isEmpty {
                    out.append("if [[ -z \"$\(parameter.variable)\" ]]; then \(parameter.variable)=\(Shell.quote(parameter.defaultValue)); fi")
                }
            }
            out.append("")
        }

        out.append(banner("Helpers"))
        out.append(helpers(settings: settings, usesDialog: usesDialog, steps: steps))

        out.append(banner("Steps"))
        for (index, step) in steps.enumerated() {
            let next = index + 1 < steps.count ? "step_\(index + 2)" : ""
            out.append(function(for: step, name: "step_\(index + 1)", next: next, names: names))
            out.append("")
        }

        out.append(banner("Main"))
        out.append("log \"Starting\"")
        out.append("if [[ $EUID -ne 0 ]]; then log \"Warning: not running as root; Jamf actions and installs may fail\"; fi")
        if settings.caffeinate { out.append("/usr/bin/caffeinate -dimsu -w $$ &") }
        if settings.waitForUser { out.append("wait_for_user") }
        out.append("loggedInUser=\"$(current_user)\"")
        out.append("loggedInUserID=\"$(/usr/bin/id -u \"$loggedInUser\" 2>/dev/null)\"")
        out.append("log \"Logged-in user: ${loggedInUser:-none}\"")
        if usesDialog { out.append("ensure_dialog") }
        out.append("")
        out.append("nextStep=" + (steps.isEmpty ? "\"\"" : "\"step_1\""))
        out.append("while [[ -n \"$nextStep\" ]]; do")
        out.append("    currentStep=\"$nextStep\"")
        out.append("    nextStep=\"\"")
        out.append("    \"$currentStep\"")
        out.append("done")
        out.append("")
        out.append("log \"Finished\"")
        out.append("exit 0")
        return out.joined(separator: "\n") + "\n"
    }

    // MARK: Pieces

    private static func oneLine(_ text: String) -> String {
        text.replacingOccurrences(of: "\n", with: " ").replacingOccurrences(of: "\r", with: " ")
    }

    private static func banner(_ title: String) -> String {
        "# " + String(repeating: "-", count: 76) + "\n# " + title + "\n# " + String(repeating: "-", count: 76)
    }

    /// Prefix for lines that must stay at column 0 (here-document bodies and terminators).
    private static let noIndent = "\u{E001}"

    private static func verbatim(_ text: String) -> String {
        text.split(separator: "\n", omittingEmptySubsequences: false)
            .map { noIndent + $0 }
            .joined(separator: "\n")
    }

    private static func indent(_ text: String, by level: Int = 1) -> String {
        let pad = String(repeating: "    ", count: level)
        return text.split(separator: "\n", omittingEmptySubsequences: false)
            .map { line -> String in
                // Kept marked so nested indentation leaves it alone; stripped when the function is assembled.
                if line.hasPrefix(noIndent) { return String(line) }
                return line.isEmpty ? "" : pad + line
            }
            .joined(separator: "\n")
    }

    /// User-written shell is indented for readability unless it contains a here-document,
    /// whose terminator would stop matching.
    private static func userShell(_ text: String) -> String {
        text.contains("<<") ? verbatim(text) : text
    }

    private static func helpers(settings: ScriptSettings, usesDialog: Bool, steps: [FlowStep]) -> String {
        var parts: [String] = []
        parts.append("""
        log() {
            local line="$(/bin/date '+%Y-%m-%d %H:%M:%S') [${scriptName}] $1"
            echo "$line"
            echo "$line" >> "$scriptLog" 2>/dev/null
        }

        cleanup() {
            [[ -n "$commandFile" ]] && /bin/rm -f "$commandFile"
            local file
            for file in "${temporaryFiles[@]}"; do /bin/rm -f "$file"; done
        }
        trap cleanup EXIT

        current_user() {
            /usr/sbin/scutil <<< "show State:/Users/ConsoleUser" | /usr/bin/awk '/Name :/ && !/loginwindow/ { print $3 }'
        }

        wait_for_user() {
            until [[ -n "$(current_user)" ]] && /usr/bin/pgrep -q -x Finder && /usr/bin/pgrep -q -x Dock; do
                sleep 2
            done
        }

        # Runs a command in the logged-in user's session when the script is running as root.
        run_as_user() {
            if [[ $EUID -eq 0 && -n "$loggedInUser" && -n "$loggedInUserID" ]]; then
                /bin/launchctl asuser "$loggedInUserID" /usr/bin/sudo -u "$loggedInUser" "$@"
            else
                "$@"
            fi
        }
        """)

        if usesDialog {
            parts.append("""
            dialog_is_current() {
                [[ -x "$dialogBinary" ]] || return 1
                [[ -z "$minimumDialogVersion" ]] && return 0
                local installed="$("$dialogBinary" --version 2>/dev/null)"
                autoload -Uz is-at-least
                is-at-least "$minimumDialogVersion" "$installed"
            }
            """)
            switch settings.installMethod {
            case .none:
                parts.append("""
                install_dialog() {
                    log "swiftDialog ${minimumDialogVersion} or later is required and is not installed"
                    return 1
                }
                """)
            case .jamfPolicy:
                parts.append("""
                install_dialog() {
                    log "Installing swiftDialog with Jamf policy event \(settings.installPolicyEvent)"
                    "$jamfBinary" policy -event \(Shell.quote(settings.installPolicyEvent)) >> "$scriptLog" 2>&1
                }
                """)
            case .github:
                parts.append("""
                # Downloads the latest swiftDialog release and installs it only if it is signed
                # by the swiftDialog developer's Team ID.
                install_dialog() {
                    local expectedTeamID="PWA5E9TQ59"
                    local workDir="$(/usr/bin/mktemp -d /private/tmp/swiftdialog.XXXXXX)"
                    local pkgURL="$(/usr/bin/curl -L --silent --fail "https://api.github.com/repos/swiftDialog/swiftDialog/releases/latest" | /usr/bin/awk -F '"' '/browser_download_url/ && /\\.pkg"/ { print $4; exit }')"
                    local result=1
                    if [[ -n "$pkgURL" ]] && /usr/bin/curl -L --silent --fail -o "$workDir/Dialog.pkg" "$pkgURL"; then
                        local teamID="$(/usr/sbin/spctl -a -vv -t install "$workDir/Dialog.pkg" 2>&1 | /usr/bin/awk '/origin=/ { print $NF }' | /usr/bin/tr -d '()')"
                        if [[ "$teamID" == "$expectedTeamID" ]]; then
                            /usr/sbin/installer -pkg "$workDir/Dialog.pkg" -target / >> "$scriptLog" 2>&1 && result=0
                        else
                            log "swiftDialog package Team ID '${teamID}' does not match ${expectedTeamID}; not installing"
                        fi
                    else
                        log "Could not download swiftDialog"
                    fi
                    /bin/rm -rf "$workDir"
                    return $result
                }
                """)
            }
            parts.append("""
            ensure_dialog() {
                dialog_is_current && return 0
                log "swiftDialog is missing or older than ${minimumDialogVersion}"
                install_dialog
                if ! dialog_is_current; then
                    log "swiftDialog is not available; exiting"
                    exit 1
                fi
            }

            run_dialog() {
                if [[ "$runDialogAsUser" == "true" ]]; then
                    run_as_user "$dialogBinary" "$@"
                else
                    "$dialogBinary" "$@"
                fi
            }

            # Sends a command to the running dialog, e.g. dialog_update "progresstext: Working…"
            dialog_update() {
                [[ -n "$commandFile" ]] && echo "$1" >> "$commandFile"
            }

            # json_value <json> <key> – prints one value from swiftDialog's --json output.
            json_value() {
                JSON_DATA="$1" JSON_KEY="$2" /usr/bin/osascript -l JavaScript -e 'function run() {
                    const env = $.NSProcessInfo.processInfo.environment;
                    let data;
                    try { data = JSON.parse(ObjC.unwrap(env.objectForKey("JSON_DATA"))); } catch (error) { return ""; }
                    let value = data[ObjC.unwrap(env.objectForKey("JSON_KEY"))];
                    if (value === undefined || value === null) { return ""; }
                    if (typeof value === "object") {
                        value = value.selectedValue !== undefined ? value.selectedValue : JSON.stringify(value);
                    }
                    return String(value);
                }' 2>/dev/null
            }
            """)
        }

        if steps.contains(where: { $0.kind == .progress }) {
            parts.append("""
            wait_for_path() {
                local target="$1" timeout="${2:-900}" waited=0
                until [[ -e "$target" ]]; do
                    sleep 2
                    waited=$((waited + 2))
                    [[ $waited -ge $timeout ]] && return 1
                done
                return 0
            }

            # run_task <list index> <progress text> <skip-if path> <success path> <command> [arguments…]
            run_task() {
                local index="$1" text="$2" skipPath="$3" successPath="$4"
                shift 4
                dialog_update "progresstext: ${text}"
                if [[ -n "$skipPath" && -e "$skipPath" ]]; then
                    dialog_update "listitem: index: ${index}, status: success, statustext: Already done"
                    dialog_update "progress: increment 1"
                    return 0
                fi
                dialog_update "listitem: index: ${index}, status: wait, statustext: Working…"
                local result=0
                "$@" >> "$scriptLog" 2>&1 || result=$?
                if [[ $result -eq 0 && -n "$successPath" && ! -e "$successPath" ]]; then result=1; fi
                if [[ $result -eq 0 ]]; then
                    dialog_update "listitem: index: ${index}, status: success, statustext: Done"
                else
                    dialog_update "listitem: index: ${index}, status: fail, statustext: Failed"
                    log "Task failed (${result}): ${text}"
                fi
                dialog_update "progress: increment 1"
                return $result
            }
            """)
        }
        return parts.map { dedent($0) }.joined(separator: "\n\n") + "\n"
    }

    /// Multi-line string literals above are indented with the Swift source; this is a no-op
    /// safeguard that trims any common leading whitespace.
    private static func dedent(_ text: String) -> String {
        let lines = text.split(separator: "\n", omittingEmptySubsequences: false)
        let indents = lines.filter { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
            .map { $0.prefix(while: { $0 == " " }).count }
        guard let common = indents.min(), common > 0 else { return text }
        return lines.map { $0.count >= common ? String($0.dropFirst(common)) : String($0) }.joined(separator: "\n")
    }

    private static func function(for step: FlowStep, name: String, next: String, names: [UUID: String]) -> String {
        var body: [String] = []
        if !step.condition.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            body.append("if ! {")
            body.append("    " + oneLine(step.condition.trimmingCharacters(in: .whitespacesAndNewlines)))
            body.append("}; then")
            body.append("    log " + Shell.quote("Skipping: " + step.name))
            body.append("    nextStep=\"\(next)\"")
            body.append("    return")
            body.append("fi")
        }
        body.append("log " + Shell.quote("Step: " + step.name))

        switch step.kind {
        case .dialog:
            body += dialogBody(step, next: next, selfName: name, names: names)
        case .progress:
            body += progressBody(step, next: next)
        case .notification:
            body += argumentLines(for: effectiveSpec(for: step), captureJSON: false)
            body.append("run_dialog \"${dialogArgs[@]}\" > /dev/null 2>&1")
            body.append("nextStep=\"\(next)\"")
        case .jamf:
            body += jamfBody(step)
            body.append("nextStep=\"\(next)\"")
        case .script:
            // Set first so the script can override it, e.g. nextStep="" to end the flow.
            body.append("nextStep=\"\(next)\"")
            let script = step.script.trimmingCharacters(in: .newlines)
            if !script.isEmpty { body.append(userShell(script)) }
        }

        let text = "# \(step.kind.label): \(oneLine(step.name))\n\(name)() {\n"
            + body.map { indent($0) }.joined(separator: "\n") + "\n}"
        return text.replacingOccurrences(of: noIndent, with: "")
    }

    /// Lines that build the `dialogArgs` array for a spec.
    private static func argumentLines(for spec: DialogSpec, captureJSON: Bool) -> [String] {
        var lines: [String] = []
        var groups: [[String]]
        if spec.usesCards {
            let config = DialogBuilder.jsonConfig(for: spec)
            lines.append("local jsonFile=\"$(/usr/bin/mktemp /private/tmp/dialogforge-json.XXXXXX)\"")
            lines.append("temporaryFiles+=(\"$jsonFile\")")
            lines.append("/bin/chmod 644 \"$jsonFile\"")
            lines.append("# Variables are expanded inside this JSON; they must not contain double quotes.")
            lines.append("/bin/cat > \"$jsonFile\" <<DIALOGFORGE_JSON")
            lines.append(verbatim(Shell.escapeForHeredoc(config.json.serialized(pretty: true))))
            lines.append(noIndent + "DIALOGFORGE_JSON")
            groups = [["--jsonfile", "$jsonFile"]] + config.extraArguments
        } else {
            groups = DialogBuilder.argumentGroups(for: spec)
        }
        if captureJSON && !spec.has("json") { groups.append(["--json"]) }
        lines.append("local -a dialogArgs")
        lines.append("dialogArgs=(")
        for group in groups {
            lines.append("    " + group.map { Shell.quote($0) }.joined(separator: " "))
        }
        lines.append(")")
        return lines
    }

    private static func dialogBody(_ step: FlowStep, next: String, selfName: String, names: [UUID: String]) -> [String] {
        let spec = effectiveSpec(for: step)
        let captures = DialogBuilder.captures(for: spec)
        var lines = argumentLines(for: spec, captureJSON: !captures.isEmpty)
        lines.append("local output exitCode")
        lines.append("output=\"$(run_dialog \"${dialogArgs[@]}\")\"")
        lines.append("exitCode=$?")
        lines.append("log \"swiftDialog exited with code ${exitCode}\"")

        if !captures.isEmpty {
            let always = spec.has("alwaysreturninput")
            if !always { lines.append("if [[ $exitCode -eq 0 ]]; then") }
            for capture in captures {
                let line = "\(capture.variable)=\"$(json_value \"$output\" \(Shell.quote(capture.outputKey)))\""
                lines.append(always ? line : "    " + line)
            }
            if !always { lines.append("fi") }
        }

        var outcomes = step.outcomes.filter { $0.code != ExitOutcome.anyOtherCode }
        outcomes.sort { $0.code < $1.code }
        let fallback = step.outcomes.first { $0.code == ExitOutcome.anyOtherCode }
        lines.append("case $exitCode in")
        var seen: Set<Int> = []
        for outcome in outcomes where !seen.contains(outcome.code) {
            seen.insert(outcome.code)
            lines.append("    \(outcome.code))")
            lines += outcomeLines(outcome, next: next, selfName: selfName, names: names).map { indent($0, by: 2) }
            lines.append("        ;;")
        }
        lines.append("    *)")
        if let fallback = fallback {
            lines += outcomeLines(fallback, next: next, selfName: selfName, names: names).map { indent($0, by: 2) }
        } else {
            lines.append("        nextStep=\"\(next)\"")
        }
        lines.append("        ;;")
        lines.append("esac")
        return lines
    }

    private static func outcomeLines(_ outcome: ExitOutcome, next: String, selfName: String, names: [UUID: String]) -> [String] {
        var lines: [String] = []
        let command = outcome.command.trimmingCharacters(in: .whitespacesAndNewlines)
        if !command.isEmpty {
            lines += [userShell(command)]
        }
        switch outcome.action {
        case .next:
            lines.append("nextStep=\"\(next)\"")
        case .retry:
            lines.append("nextStep=\"\(selfName)\"")
        case .goto:
            let target = outcome.targetStep.flatMap { names[$0] } ?? next
            lines.append("nextStep=\"\(target)\"")
        case .exit:
            lines.append("log \"Exiting with status \(outcome.exitStatus)\"")
            lines.append("exit \(outcome.exitStatus)")
        }
        return lines
    }

    static func taskCommand(_ task: ProgressTask) -> String {
        let value = task.value.trimmingCharacters(in: .whitespacesAndNewlines)
        switch task.action {
        case .policyEvent:
            return "\"$jamfBinary\" policy -event " + Shell.quote(value)
        case .policyID:
            return "\"$jamfBinary\" policy -id " + Shell.quote(value)
        case .command:
            return "/bin/zsh -c " + Shell.quote(value.isEmpty ? "true" : value)
        case .waitForPath:
            return "wait_for_path " + Shell.quote(value)
        case .pause:
            return "/bin/sleep " + Shell.quote(value.isEmpty ? "1" : value)
        }
    }

    private static func progressBody(_ step: FlowStep, next: String) -> [String] {
        var lines: [String] = []
        lines.append("commandFile=\"$(/usr/bin/mktemp /private/tmp/dialogforge-command.XXXXXX)\"")
        lines.append("/bin/chmod 644 \"$commandFile\"")
        lines += argumentLines(for: effectiveSpec(for: step), captureJSON: false)
        lines.append("run_dialog \"${dialogArgs[@]}\" &")
        lines.append("local dialogPID=$!")
        lines.append("sleep 1")
        lines.append("local failures=0")
        lines.append("")
        for (index, task) in step.tasks.enumerated() {
            let text = task.progressText.isEmpty ? task.title : task.progressText
            lines.append("run_task \(index) \(Shell.quote(text)) \(Shell.quote(task.skipIfPath)) \(Shell.quote(task.successPath)) \\")
            lines.append("    " + taskCommand(task) + " || failures=$((failures + 1))")
        }
        lines.append("")
        lines.append("dialog_update \"progress: complete\"")
        lines.append("if [[ $failures -eq 0 ]]; then")
        lines.append("    dialog_update " + Shell.quote("progresstext: " + step.completionText))
        lines.append("else")
        lines.append("    dialog_update \"progresstext: Finished with ${failures} problem(s)\"")
        lines.append("fi")
        switch step.completion {
        case .waitForButton:
            if !step.completionButtonText.isEmpty {
                lines.append("dialog_update " + Shell.quote("button1text: " + step.completionButtonText))
            }
            lines.append("dialog_update \"button1: enable\"")
        case .autoClose:
            lines.append("sleep \(max(step.autoCloseDelay, 0))")
            lines.append("dialog_update \"quit:\"")
        }
        lines.append("wait \"$dialogPID\" 2>/dev/null")
        lines.append("/bin/rm -f \"$commandFile\"")
        lines.append("commandFile=\"\"")
        if step.stopOnFailure {
            lines.append("if [[ $failures -gt 0 ]]; then")
            lines.append("    log \"${failures} task(s) failed; exiting\"")
            lines.append("    exit 1")
            lines.append("fi")
        }
        lines.append("nextStep=\"\(next)\"")
        return lines
    }

    private static func jamfBody(_ step: FlowStep) -> [String] {
        let value = step.jamfValue.trimmingCharacters(in: .whitespacesAndNewlines)
        let arguments = step.jamfArguments.trimmingCharacters(in: .whitespacesAndNewlines)
        let suffix = arguments.isEmpty ? "" : " " + oneLine(arguments)
        var command: String
        switch step.jamfAction {
        case .policyEvent:
            command = "\"$jamfBinary\" policy -event " + Shell.quote(value) + suffix
        case .policyID:
            command = "\"$jamfBinary\" policy -id " + Shell.quote(value) + suffix
        case .recon:
            command = "\"$jamfBinary\" recon" + suffix
        case .manage:
            command = "\"$jamfBinary\" manage" + suffix
        case .selfService:
            return ["run_as_user /usr/bin/open " + Shell.quote(value.isEmpty ? "jamfselfservice://" : value)]
        }
        command += " >> \"$scriptLog\" 2>&1"
        return [command + " || log " + Shell.quote("Jamf action failed: " + step.name)]
    }
}
